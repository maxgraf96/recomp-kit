#!/usr/bin/env python3
"""Generate runtime/msvcrt_unicode.h: wide-character tables for the C runtime HLE.

The tables come from the Unicode Character Database as Python's unicodedata
module ships it, not from any Windows file:
  - simple 1:1 upper/lower case mappings over the BMP, as runs;
  - msvcrt's _ctype bits for every BMP code point (from the general category,
    the way GetStringTypeW's C1 types are described), as runs;
  - code page 1252 to UTF-16 for 0x80..0x9f (the rest is Latin-1).

Run: python3 tools/gen_msvcrt_unicode.py > runtime/msvcrt_unicode.h"""

import codecs
import sys
import unicodedata

UPPER, LOWER, DIGIT, SPACE, PUNCT, CONTROL, BLANK, HEX, ALPHA = (
    0x1, 0x2, 0x4, 0x8, 0x10, 0x20, 0x40, 0x80, 0x100)
HEX_DIGITS = set(range(0x30, 0x3A)) | set(range(0x41, 0x47)) | set(range(0x61, 0x67)) | \
    set(range(0xFF10, 0xFF1A)) | set(range(0xFF21, 0xFF27)) | set(range(0xFF41, 0xFF47))
# Latin-1 superscript digits count as digits in Microsoft's C1 data.
SUPERSCRIPT_DIGITS = {0xB2, 0xB3, 0xB9}


def ctype_bits(cp):
    cat = unicodedata.category(chr(cp))
    bits = 0
    if cat == "Lu":
        bits = UPPER | ALPHA
    elif cat == "Ll":
        bits = LOWER | ALPHA
    elif cat in ("Lt", "Lm", "Lo"):
        bits = ALPHA
    elif cat == "Nd":
        bits = DIGIT
    elif cat == "Zs":
        bits = SPACE | BLANK
    elif cat in ("Zl", "Zp"):
        bits = SPACE
    elif cat == "Cc":
        bits = CONTROL
        if cp in (0x09, 0x0A, 0x0B, 0x0C, 0x0D):
            bits |= SPACE
        if cp == 0x09:
            bits |= BLANK
    elif cat[0] in "PS" or cat in ("No", "Nl", "Cf", "Mn", "Mc", "Me"):
        bits = PUNCT
    if cp in SUPERSCRIPT_DIGITS:
        bits |= DIGIT
    if cp in HEX_DIGITS:
        bits |= HEX
    return bits


def case_runs(fn):
    m = {}
    for cp in range(0x10000):
        if 0xD800 <= cp < 0xE000:
            continue
        r = fn(chr(cp))
        if len(r) == 1 and ord(r) != cp and ord(r) < 0x10000:
            m[cp] = ord(r)
    keys = sorted(m)
    out, i = [], 0
    while i < len(keys):
        k, d = keys[i], m[keys[i]] - keys[i]
        for stride in (1, 2):
            j = i
            while j + 1 < len(keys) and keys[j + 1] == keys[j] + stride and m[keys[j + 1]] - keys[j + 1] == d:
                j += 1
            if j > i:
                break
        out.append((k, keys[j], d, stride if j > i else 1))
        i = j + 1
    return out


def main():
    w = sys.stdout.write
    w("// msvcrt_unicode.h - generated by tools/gen_msvcrt_unicode.py from the Unicode\n")
    w("// Character Database %s. Do not edit by hand.\n" % unicodedata.unidata_version)
    w("#pragma once\n#include <stdint.h>\n\n// clang-format off\nnamespace crt {\n\n")
    w("struct CaseRun {\n    uint16_t first, last;\n    int32_t delta;\n    uint8_t stride;\n};\n\n")
    for name, fn in (("kUpperRuns", str.upper), ("kLowerRuns", str.lower)):
        runs = case_runs(fn)
        w("static const CaseRun %s[] = {\n" % name)
        for first, last, delta, stride in runs:
            w("    {0x%04x, 0x%04x, %d, %d},\n" % (first, last, delta, stride))
        w("};\n\n")
    w("struct CtypeRun {\n    uint16_t first;\n    uint16_t bits;\n};\n\n")
    w("// Each run covers [first, next run's first).\nstatic const CtypeRun kCtypeRuns[] = {\n")
    prev = None
    line = []
    for cp in range(0x10000):
        b = 0 if 0xD800 <= cp < 0xE000 else ctype_bits(cp)
        if b != prev:
            line.append("{0x%04x, 0x%03x}" % (cp, b))
            prev = b
    for i in range(0, len(line), 5):
        w("    " + ", ".join(line[i:i + 5]) + ",\n")
    w("};\n\n")
    w("// Code page 1252, 0x80..0x9f; undefined bytes map to the C1 control of the same value.\n")
    w("static const uint16_t kCp1252High[32] = {\n")
    vals = []
    for b in range(0x80, 0xA0):
        try:
            vals.append(ord(codecs.decode(bytes([b]), "cp1252")))
        except UnicodeDecodeError:
            vals.append(b)
    for i in range(0, 32, 8):
        w("    " + ", ".join("0x%04x" % v for v in vals[i:i + 8]) + ",\n")
    w("};\n\n} // namespace crt\n// clang-format on\n")


if __name__ == "__main__":
    main()
